import os
import sys
import time
from pathlib import Path
 
REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO))
os.environ["SPARK_CONF_DIR"] = str(REPO / "conf")
 
from pyspark.sql import SparkSession, Window  # noqa: E402
from pyspark.sql import functions as F  # noqa: E402
 
SILVER_DIR = REPO / "data" / "silver"
CATALOG_FILE = REPO / "data" / "catalog" / "products.json"
DIM_PRODUCT_DIR = REPO / "data" / "warehouse" / "dim_product"
 
OPEN_DATE = "9999-12-31"  # valid_to sentinel for the current version
 
 
def read_silver_events(spark):
    if not SILVER_DIR.exists() or not any(SILVER_DIR.iterdir()):
        print(f"{SILVER_DIR} is empty. Run processing/batch_silver.py first.")
        sys.exit(1)
    return spark.read.parquet(str(SILVER_DIR)).select(
        "product_id", "event_time", "price", "brand",
        "category_id", "category_code",
        "category_l1", "category_l2", "category_l3",
        "user_session",
    )
 
 
def read_catalog(spark):
    if not CATALOG_FILE.exists():
        print(f"{CATALOG_FILE} is missing. Run ingestion/gen_catalog.py first.")
        sys.exit(1)
    # products.json is JSON Lines, generated by our own script, so
    # letting Spark infer the nested schema is safe here — unlike the
    # raw CSV, there is no ambiguous INT/BIGINT column to get wrong.
    return spark.read.json(str(CATALOG_FILE)).select("product_id", "attributes")
 
 
def assign_versions(events):
    """One pass over silver: detect every price change per product and
    assign version_no AND product_sk directly onto the event row.
 
    Ordering: partitioned by product_id, ordered by (event_time,
    user_session). event_time alone is not always unique to the second,
    so user_session is a deterministic tie-breaker — it does not
    recover true sub-second order, but it makes the assignment
    byte-identical across all four machines, which is the property that
    actually matters here (the same one CLAUDE.md's hash-based sampling
    protects). Worth a line in the report, not a defect.
 
    Change detection uses eqNullSafe, per PLAN.md's SCD2 warning: `<>`
    would treat NULL <> NULL as NULL rather than true. price is NOT
    NULL in silver (rule 1 drops price <= 0), so this is technically
    unnecessary here the way it is NOT unnecessary for dim_user.rfm_cell
    -- eqNullSafe is used anyway so the two SCD2 builds in this repo
    follow one rule, not two.
    """
    order_w = Window.partitionBy("product_id").orderBy("event_time", "user_session")
    running_w = order_w.rowsBetween(Window.unboundedPreceding, Window.currentRow)
 
    prev_price = F.lag("price").over(order_w)
    # eqNullSafe(NULL, price) is False -> "not equal" is True, so the
    # very first event of a product is flagged as a change for free and
    # version_no starts at 1 with no separate first-row case.
    changed = (~F.col("price").eqNullSafe(prev_price)).cast("int")
 
    versioned = (
        events
        .withColumn("changed", changed)
        .withColumn("version_no", F.sum("changed").over(running_w))
        .drop("changed")
    )
 
    # Small window on purpose: distinct (product_id, version_no) pairs
    # are ~100-250K rows (measure with dim_product's own report(), not
    # guessed), nowhere near fact_event's 4.7M. Spark will warn "No
    # Partition Defined for Window operation" because row_number here
    # is intentionally global, not per-product -- product_sk must be
    # unique across the whole table, not just within one product.
    sk_w = Window.orderBy("product_id", "version_no")
    product_sk = (
        versioned.select("product_id", "version_no").distinct()
        .withColumn("product_sk", F.row_number().over(sk_w))
    )
    return versioned.join(product_sk, ["product_id", "version_no"], "left")
 
 
def build_dim_product(versioned_events, catalog):
    """Collapse the event-level, per-version rows from assign_versions()
    into one row per (product_id, version_no) -- the actual dim_product
    table.
 
    Type 1 attributes (brand, category_*) take the value observed on
    the most recent event inside that price-version window via
    max_by(col, event_time): REES46 gives no authoritative source for
    "the current brand", so this build treats the latest sighting
    within the version as the truth for that version. That is a
    simplification worth stating in the report, not a hidden defect --
    a stricter Type 1 rule would overwrite the value across ALL
    historical versions on every rebuild, which this batch does not do.
    """
    versions = (
        versioned_events.groupBy("product_id", "version_no")
        .agg(
            F.min("event_time").alias("valid_from_ts"),
            F.first("price", ignorenulls=True).alias("price"),  # constant within a version by construction
            F.max_by("brand", "event_time").alias("brand"),
            F.max_by("category_id", "event_time").alias("category_id"),
            F.max_by("category_code", "event_time").alias("category_code"),
            F.max_by("category_l1", "event_time").alias("category_l1"),
            F.max_by("category_l2", "event_time").alias("category_l2"),
            F.max_by("category_l3", "event_time").alias("category_l3"),
            F.first("product_sk").alias("product_sk"),
        )
        .withColumn("valid_from", F.to_date("valid_from_ts"))
        .drop("valid_from_ts")
    )
 
    next_w = Window.partitionBy("product_id").orderBy("version_no")
    open_date = F.lit(OPEN_DATE).cast("date")
    versions = (
        versions
        .withColumn("next_valid_from", F.lead("valid_from").over(next_w))
        .withColumn("valid_to", F.coalesce("next_valid_from", open_date))
        .withColumn("is_current", F.col("valid_to") == open_date)
        .drop("next_valid_from")
    )
 
    dim_product = versions.join(catalog, "product_id", "left")
 
    # Every product_id here comes from silver, and gen_catalog.py reads
    # its ids from that same silver, so this should never fire. If it
    # does, the catalog is stale (built before the current silver) --
    # fail loudly rather than write a NULL into a NOT NULL jsonb column.
    missing = dim_product.filter(F.col("attributes").isNull()).count()
    if missing:
        raise RuntimeError(
            f"{missing} dim_product rows have no catalog attributes. "
            "Re-run ingestion/gen_catalog.py against the current data/silver/."
        )
 
    return dim_product.select(
        "product_sk", "product_id", "version_no", "price",
        "brand", "category_id", "category_code",
        "category_l1", "category_l2", "category_l3",
        "attributes", "valid_from", "valid_to", "is_current",
    )
 
 
def write_dim_product(dim_product) -> None:
    (
        dim_product
        .sortWithinPartitions("product_id", "version_no")
        .coalesce(1)
        .write.mode("overwrite")
        .parquet(str(DIM_PRODUCT_DIR))
    )
 
 
def report(spark) -> bool:
    """Read dim_product back from disk and check the two SCD2
    invariants PLAN.md's W44 correctness metric names explicitly:
    valid_from/valid_to intervals must not overlap, and exactly one row
    per product_id must be is_current. Prints measured counts rather
    than asserting fixed EXPECTED numbers -- unlike bronze/silver, no
    prior run of this script exists yet to pin them against (see
    SYSTEM_DESIGN.md 3.1: re-measure everything derived from the star
    in W39)."""
    df = spark.read.parquet(str(DIM_PRODUCT_DIR))
 
    n_versions = df.count()
    n_products = df.select("product_id").distinct().count()
 
    bad_current = (
        df.groupBy("product_id")
        .agg(F.sum(F.col("is_current").cast("int")).alias("n_current"))
        .filter("n_current != 1")
        .count()
    )
 
    w = Window.partitionBy("product_id").orderBy("valid_from")
    overlaps = (
        df.withColumn("next_valid_from", F.lead("valid_from").over(w))
        .filter(
            F.col("next_valid_from").isNotNull()
            & (F.col("next_valid_from") != F.col("valid_to"))
        )
        .count()
    )
 
    bad_range = df.filter(F.col("valid_from") >= F.col("valid_to")).count()
    null_l1 = df.filter(F.col("category_l1").isNull()).count()
    null_attrs = df.filter(F.col("attributes").isNull()).count()
 
    print(f"products                {n_products:>10,}")
    print(f"product versions        {n_versions:>10,}")
    print(f"products with != 1 is_current row   {bad_current:>6,}   (expect 0)")
    print(f"overlapping/gapped SCD2 intervals    {overlaps:>6,}   (expect 0)")
    print(f"valid_from >= valid_to               {bad_range:>6,}   (expect 0)")
    print(f"null category_l1                     {null_l1:>6,}   (expect 0)")
    print(f"null attributes                       {null_attrs:>6,}   (expect 0)")
 
    return bad_current == 0 and overlaps == 0 and bad_range == 0 and null_l1 == 0 and null_attrs == 0
 
 
def main():
    start = time.time()
    spark = (
        SparkSession.builder
        .appName("dim_product")
        .master("local[*]")
        .getOrCreate()
    )
    try:
        events = read_silver_events(spark)
        catalog = read_catalog(spark)
        versioned_events = assign_versions(events)
        dim_product = build_dim_product(versioned_events, catalog)
        write_dim_product(dim_product)
        ok = report(spark)
    finally:
        spark.stop()
 
    took = time.time() - start
    print(f"took                    {took:>9.0f} s")
    if not ok:
        print("DIM_PRODUCT CHECK FAILED")
        sys.exit(1)
    print("DIM_PRODUCT OK")
 
 
if __name__ == "__main__":
    main()
 