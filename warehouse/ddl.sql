-- ShopInsight - the PostgreSQL star schema, SYSTEM_DESIGN.md sections 5.4 and 5.5
-- warehouse/ddl.sql
--
-- Apply once, to an EMPTY database, then load the three small dimensions:
--   docker exec -i shopinsight-postgres psql -U shopinsight -d shopinsight -v ON_ERROR_STOP=1 < warehouse/ddl.sql
--   python serving/load_star_postgres.py
--
-- There is no IF NOT EXISTS on purpose. Applied over an older schema, IF NOT EXISTS
-- skipped every table, printed notices, exited 0 and kept the old shape. Plain CREATE
-- inside one transaction fails at the first table and rolls everything back; under
-- ON_ERROR_STOP psql then exits 3. To start again (this wipes that database):
--   docker exec shopinsight-postgres psql -U shopinsight -d shopinsight -c 'DROP SCHEMA public CASCADE; CREATE SCHEMA public;'
--
-- Between BEGIN and COMMIT this is SYSTEM_DESIGN.md 5.4/5.5 verbatim. A change starts
-- there and is copied here. Two differences:
--   - no INSERT INTO dim_event_type, marked "-- not in 5.4". serving/load_star_postgres.py
--     writes the five rows; the Spark build (processing/batch_warehouse.py) writes
--     the same rows to Parquet.
--   - the CREATE TABLE ... PARTITION OF statements. 5.5 says in a comment which
--     partitions exist and that this file creates them; the statements spell them out.
--
-- W39 loads the three small dims only (dim_date, dim_event_type, dim_warehouse);
-- dim_product, dim_user and the three facts stay empty until the Spark build.
-- docs/evidence/explain_fact_event_partition.sql shows the plans on this schema.

