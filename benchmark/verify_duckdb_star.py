#!/usr/bin/env python3
"""Check that DuckDB reads every table of the Parquet star schema and counts the right rows.

    python benchmark/verify_duckdb_star.py [--warehouse-dir PATH]

Task: W42 Task 99 (Tin), the ground-truth base for the W43/W44 evaluation. data/ is
gitignored, so by default this reads data/warehouse/ next to this repo; --warehouse-dir
points it at another build (for example the main checkout's data/warehouse from a git
worktree, whose own data/ is empty).

Tables checked (all written by processing/batch_warehouse.py):
  - dim_date             calendar 2019-10-01 .. 2019-12-31, generated by
                         build_dim_date_rows() in serving/load_star_postgres.py,
                         is_holiday from seed/holidays_2019.csv
  - dim_event_type       5 fixed rows (DIM_EVENT_TYPE_ROWS, same file)
  - dim_warehouse        5 synthetic warehouses (DIM_WAREHOUSE_ROWS, same file)
  - dim_product          SCD Type 2
  - dim_user             SCD Type 2, built from the stg_rfm_snapshot staging table
  - fact_event           transaction fact, partitioned by event_date
  - fact_session_funnel  accumulating snapshot, partitioned by session_start_date
  - fact_inventory_daily periodic snapshot, partitioned by snapshot_date

EXPECTED_COUNTS are the counts DuckDB returned on 10 Nov 2026 for the build in the
main checkout's data/warehouse/. A rebuild from the same CSV gives the same counts
(the 7% user sample is a deterministic hash). Prints DUCKDB STAR OK and exits 0 when
every table matches, otherwise exits 1.
"""

import argparse
import sys
from pathlib import Path

import duckdb

REPO = Path(__file__).resolve().parent.parent
DEFAULT_WAREHOUSE_DIR = REPO / "data" / "warehouse"

EXPECTED_COUNTS = {
    "dim_date": 92,
    "dim_event_type": 5,
    "dim_warehouse": 5,
    "dim_product": 210_454,
    "dim_user": 319_426,
    "fact_event": 4_754_015,
    "fact_session_funnel": 970_797,
    "fact_inventory_daily": 1_909_650,
}


def count_rows(con, warehouse_dir, table):
    """Count the rows of one Parquet table with DuckDB, or return None if it has no files."""
    table_dir = warehouse_dir / table
    if not any(table_dir.rglob("*.parquet")):
        return None
    pattern = (table_dir / "**" / "*.parquet").as_posix()
    return con.execute(
        f"SELECT count(*) FROM read_parquet('{pattern}', hive_partitioning=true)"
    ).fetchone()[0]


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--warehouse-dir", type=Path, default=DEFAULT_WAREHOUSE_DIR,
                        help="the Parquet star to check (default: data/warehouse in this repo)")
    args = parser.parse_args()
    warehouse_dir = args.warehouse_dir.resolve()

    print(f"DuckDB {duckdb.__version__} on {warehouse_dir}")
    if not warehouse_dir.is_dir():
        print("No warehouse directory. data/ is gitignored: run processing/batch_warehouse.py "
              "first, or pass --warehouse-dir.")
        sys.exit(1)

    con = duckdb.connect()
    failures = 0
    for table, expected in EXPECTED_COUNTS.items():
        actual = count_rows(con, warehouse_dir, table)
        if actual is None:
            status = "MISSING (no Parquet files)"
            failures += 1
        elif actual == expected:
            status = "OK"
        else:
            status = f"MISMATCH (expected {expected:,})"
            failures += 1
        shown = "-" if actual is None else f"{actual:,}"
        print(f"  {table:<22}{shown:>12}  {status}")

    if failures:
        print(f"{failures} table(s) failed")
        sys.exit(1)
    print("DUCKDB STAR OK")


if __name__ == "__main__":
    main()
